import {mkdir, readFile, writeFile} from 'node:fs/promises'
import {compile} from '@ohm-js/compiler'

const grammarFile = new URL('../packages/oldm-turtle/experimental/turtle.ohm', import.meta.url)
const outputFile = new URL('../packages/oldm-turtle/experimental/turtle-ohm18.wasm', import.meta.url)
const bytesModuleFile = new URL('../packages/oldm-turtle/src/generated/turtle-ohm18-wasm.mjs', import.meta.url)

const source = await readFile(grammarFile, 'utf8')
const bytes = compile(source, {grammarName: 'TurtleSubset'})
await writeFile(outputFile, bytes)
await mkdir(new URL('../packages/oldm-turtle/src/generated/', import.meta.url), {recursive: true})
await writeFile(bytesModuleFile, `// Generated by scripts/compile-ohm-turtle.mjs. Do not edit by hand.\nconst encoded = '${Buffer.from(bytes).toString('base64')}'\n\nfunction decodeBase64(value) {\n\tif (typeof atob == 'function') {\n\t\treturn atob(value)\n\t}\n\treturn globalThis.Buffer.from(value, 'base64').toString('binary')\n}\n\nexport default function turtleOhm18WasmBytes() {\n\tconst binary = decodeBase64(encoded)\n\tconst bytes = new Uint8Array(binary.length)\n\tfor (let i=0; i<binary.length; i++) {\n\t\tbytes[i] = binary.charCodeAt(i)\n\t}\n\treturn bytes\n}\n`)

console.log(`Compiled ${grammarFile.pathname} -> ${outputFile.pathname} (${bytes.length} bytes)`)
console.log(`Wrote ${bytesModuleFile.pathname}`)
